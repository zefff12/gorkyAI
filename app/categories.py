"""Категория события по названию — для иконок из макета («Иконки» в Figma).

Сравниваются леммы, поэтому «Созвон с Иваном», «созвониться» и «звонок»
дают одну категорию. Порядок правил важен: первое совпадение побеждает.
"""
from __future__ import annotations

from functools import lru_cache

from .models import Event, EventType
from .nlu.text import lemmas

RULES: list[tuple[str, set[str]]] = [
    ("birthday", {"рождение", "др", "юбилей", "именины"}),
    ("party", {"вечеринка", "праздник", "корпоратив", "тусовка", "банкет", "фуршет", "отпраздновать"}),
    ("yoga", {"йога", "йог", "тренировка", "пилатес", "медитация", "фитнес", "спортзал", "зал", "бег", "пробежка",
              "растяжка", "бассейн", "спорт", "тренажёрный", "тренажерный"}),
    ("sprint", {"спринт", "соревнование", "конкурс", "хакатон", "турнир", "марафон", "олимпиада", "чемпионат"}),
    ("report", {"отчёт", "отчет", "экзамен", "сдача", "сдать", "зачёт", "зачет", "дедлайн", "акт", "смета",
                "протокол", "диплом", "курсовая", "контрольная"}),
    ("call", {"созвон", "созвониться", "звонок", "позвонить", "звонить", "видеозвонок", "zoom", "зум", "телемост"}),
    ("discussion", {"обсуждение", "обсудить", "переговоры", "совещание", "демо", "презентация", "проект",
                    "интервью", "собеседование", "согласовать", "ревью"}),
    ("team", {"команда", "планёрка", "планерка", "стендап", "ретро", "встреча", "собрание", "митинг"}),
]


@lru_cache(maxsize=4096)
def category_of_title(title: str, event_type: str) -> str | None:
    words = set(lemmas(title))
    for name, keys in RULES:
        if words & keys:
            return name
    return "team" if event_type == EventType.MEETING.value else None


def category_of(ev: Event) -> str | None:
    return category_of_title(ev.title, ev.type.value)
